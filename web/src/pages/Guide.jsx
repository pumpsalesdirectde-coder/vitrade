export default function Guide({ topic }) {
  const art = ARTICLES.find((a) => a.id === topic);
  if (art) {
    const i = ARTICLES.indexOf(art);
    const next = ARTICLES[i + 1];
    return (
      <article className="panel article">
        <a href="#/guide" className="back">← Все статьи</a>
        <p className="muted small">{art.group} · {art.time} чтения</p>
        <h2>{art.title}</h2>
        <p className="lead-text">{art.lead}</p>
        {art.body.map(([t, text], k) => (t === "h" ? <h3 key={k}>{text}</h3> : <p key={k}>{text}</p>))}
        {next && <a className="next-article" href={`#/guide/${next.id}`}><small className="muted">Дальше</small><b>{next.title}</b></a>}
      </article>
    );
  }
  const groups = [...new Set(ARTICLES.map((a) => a.group))];
  return (
    <div className="guide">
      <p className="muted">Короткие статьи о том, как работают боты и экраны MIVTrade.</p>
      {groups.map((g) => (
        <section key={g} className="guide-group">
          <h3>{g}</h3>
          <div className="guide-list">
            {ARTICLES.filter((a) => a.group === g).map((a) => (
              <a key={a.id} className="guide-item" href={`#/guide/${a.id}`}>
                <b>{a.title}</b>
                <span className="muted">{a.lead}</span>
                <small className="muted">{a.time}</small>
              </a>
            ))}
          </div>
        </section>
      ))}
    </div>
  );
}
